const PREBUILT: &str = r#"if [ ! -x /usr/local/bin/echochamber ] && ! command -v echochamber >/dev/null 2>&1; then
  echo "prebuilt image is missing the echochamber binary" >&2
  exit 1
fi
"#;

const INSTALL: &str = r#"if [ ! -x /usr/local/bin/echochamber ] && ! command -v echochamber >/dev/null 2>&1; then
  b64='@@BINARY_B64@@'
  if [ -n "$b64" ]; then
    url=$(printf '%s' "$b64" | base64 -d)
    curl -fsSL "$url" -o /usr/local/bin/echochamber
    chmod 755 /usr/local/bin/echochamber
  else
    if command -v apt-get >/dev/null 2>&1; then
      apt-get install -y build-essential pkg-config
    fi
    if ! command -v cargo >/dev/null 2>&1; then
      curl --proto '=https' --tlsv1.2 -fsSL https://sh.rustup.rs | sh -s -- -y --default-toolchain stable
    fi
    if [ -f /root/.cargo/env ]; then
      . /root/.cargo/env
    fi
    cargo install --git https://github.com/monomyth/echochamber.git --locked --root /usr/local
  fi
fi
"#;

/// Watchdog for a relay on the operator's own computer. Stops that process
/// only. It must never shut the machine down.
pub fn local_watchdog_script() -> &'static str {
    r#"#!/bin/sh
set -eu
pidfile=$1
deadline=$2
idle=$3
grace=$4
curlconf=$5
port=$6
relay=$(cat "$pidfile")
start=$(date +%s)
seen=0
down_since=0
while kill -0 "$relay" 2>/dev/null; do
  now=$(date +%s)
  if [ "$now" -ge "$deadline" ]; then
    kill -TERM "$relay" 2>/dev/null || true
    exit 0
  fi
  body=$(curl -fsS -m 3 -K "$curlconf" "http://127.0.0.1:${port}/status" || true)
  pub=0
  case "$body" in
    *'"publishing":true'*) pub=1 ;;
  esac
  if [ "$pub" = 1 ]; then
    seen=1
    down_since=0
  else
    if [ "$seen" = 1 ]; then
      if [ "$down_since" = 0 ]; then down_since=$now; fi
      if [ $((now - down_since)) -ge "$idle" ]; then
        kill -TERM "$relay" 2>/dev/null || true
        exit 0
      fi
    elif [ $((now - start)) -ge "$grace" ]; then
      kill -TERM "$relay" 2>/dev/null || true
      exit 0
    fi
  fi
  sleep 15
done
"#
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::{QualityConfig, YoutubePlatform};

    fn spec<'a>(
        prebuilt: bool,
        binary: Option<&'a str>,
        platforms: &'a Platforms,
        quality: &'a QualityConfig,
    ) -> CloudInitSpec<'a> {
        CloudInitSpec {
            stream_key: "aabbccddeeff0011",
            control_token: "00112233445566778899aabbccddeeff",
            platforms,
            quality,
            expires_at_unix: 1_800_000_000,
            idle_secs: 600,
            connect_grace_secs: 900,
            prebuilt,
            binary_url: binary,
        }
    }

    fn outside_config_block(script: &str) -> String {
        let start = script.find("<<'EOF'\n").unwrap() + "<<'EOF'\n".len();
        let end = script[start..].find("\nEOF\n").unwrap() + start;
        let mut out = String::new();
        out.push_str(&script[..start - "<<'EOF'\n".len()]);
        out.push_str(&script[end + "\nEOF\n".len()..]);
        out
    }

    #[test]
    fn control_probe_happens_before_ingest_is_opened() {
        let platforms = Platforms::default();
        let quality = QualityConfig::default();
        let script = render(&spec(true, None, &platforms, &quality)).unwrap();
        let drop_at = script
            .find("iptables -I INPUT -p tcp --dport 1935 -j DROP")
            .unwrap();
        let probe_at = script
            .find("curl -fsS -m 2 -K /etc/echochamber/curl.conf http://127.0.0.1:8080/status")
            .unwrap();
        let open_at = script
            .find("iptables -D INPUT -p tcp --dport 1935 -j DROP")
            .unwrap();
        assert!(drop_at < probe_at && probe_at < open_at, "{script}");
        assert!(script.contains("\"publishing\""));
        assert!(script.contains("shutdown -h now \"echochamber ttl\""));
        assert!(script.contains("shutdown -h now \"echochamber idle\""));
        assert!(script.contains("ECHOCHAMBER_DISABLE_DEPLOY=1"));
        assert!(!script.contains("cargo install"));
        let outside = outside_config_block(&script);
        assert!(!outside.contains("aabbccddeeff0011"));
        assert!(!outside.contains("00112233445566778899aabbccddeeff"));
        let b64_start = script.find("<<'EOF'\n").unwrap() + "<<'EOF'\n".len();
        let b64_end = script[b64_start..].find("\nEOF\n").unwrap() + b64_start;
        let decoded = STANDARD
            .decode(script[b64_start..b64_end].trim().as_bytes())
            .unwrap();
        let text = String::from_utf8(decoded).unwrap();
        assert!(text.contains("stream_key = \"aabbccddeeff0011\""));
        assert!(text.contains("token = \"00112233445566778899aabbccddeeff\""));
        assert!(text.contains("bind = \"127.0.0.1:8080\""));
    }

    #[test]
    fn fly_process_opens_ingest_only_after_status_and_then_exits() {
        let platforms = Platforms::default();
        let quality = QualityConfig::default();
        let script = render_process(&spec(true, None, &platforms, &quality)).unwrap();
        let drop_at = script
            .find("iptables -I INPUT -p tcp --dport 1935 -j DROP")
            .unwrap();
        let probe_at = script
            .find("curl -fsS -m 2 -K /etc/echochamber/curl.conf http://127.0.0.1:8080/status")
            .unwrap();
        let open_at = script
            .find("iptables -D INPUT -p tcp --dport 1935 -j DROP")
            .unwrap();
        assert!(drop_at < probe_at && probe_at < open_at, "{script}");
        assert!(script.contains("ECHOCHAMBER_DISABLE_DEPLOY=1"));
        assert!(script.contains("exit 0"));
        assert!(!script.contains("shutdown"));
        assert!(!script.contains("systemctl"));
        let outside = outside_config_block(&script);
        assert!(!outside.contains("aabbccddeeff0011"));
        assert!(!outside.contains("00112233445566778899aabbccddeeff"));
    }

    #[test]
    fn fallback_installs_and_does_not_copy_oauth_secrets() {
        let mut platforms = Platforms::default();
        platforms.youtube = Some(YoutubePlatform {
            enabled: true,
            stream_key: "ytkey".into(),
            ingest_base: None,
            client_id: None,
            client_secret: Some("oauth-secret-value".into()),
            refresh_token: None,
        });
        let quality = QualityConfig::default();
        let script = render(&spec(false, None, &platforms, &quality)).unwrap();
        assert!(script.contains("cargo install --git https://github.com/monomyth/echochamber.git"));
        assert!(!script.contains("oauth-secret-value"));
    }

    #[test]
    fn local_watchdog_kills_the_relay_and_not_the_computer() {
        let script = local_watchdog_script();
        assert!(script.contains("kill -TERM"));
        assert!(!script.contains("shutdown"));
    }
}
