use base64::engine::general_purpose::STANDARD;
use base64::Engine;

use crate::config::{Platforms, QualityConfig};

use super::error::DeployError;
use super::model::{relay_config_toml, RTMP_PORT};

/// Guest boot script. The ingest port stays dropped until `/status` on
/// loopback returns the relay JSON. The cloud firewall never opens the
/// control port; this script is what makes the controller's TCP accept mean
/// the control endpoint already answered.
pub struct CloudInitSpec<'a> {
    pub stream_key: &'a str,
    pub control_token: &'a str,
    pub platforms: &'a Platforms,
    pub quality: &'a QualityConfig,
    pub expires_at_unix: u64,
    pub idle_secs: u64,
    pub connect_grace_secs: u64,
    pub prebuilt: bool,
    pub binary_url: Option<&'a str>,
}

pub fn render(spec: &CloudInitSpec<'_>) -> Result<String, DeployError> {
    finish_script(fill(SCRIPT, spec))
}

/// Fly's init is the main process, not systemd. The same gate holds port
/// 1935 closed until loopback `/status` answers. Exiting is what ends the
/// machine: `auto_destroy` plus a restart policy of `no`.
pub fn render_process(spec: &CloudInitSpec<'_>) -> Result<String, DeployError> {
    finish_script(fill(PROCESS, spec))
}

fn fill(template: &str, spec: &CloudInitSpec<'_>) -> String {
    let config = relay_config_toml(
        &format!("0.0.0.0:{RTMP_PORT}"),
        "127.0.0.1:8080",
        spec.stream_key,
        spec.control_token,
        spec.platforms,
        spec.quality,
    );
    let config_b64 = STANDARD.encode(config.as_bytes());
    let binary_b64 = match spec.binary_url {
        Some(url) => STANDARD.encode(url.as_bytes()),
        None => String::new(),
    };
    let install = if spec.prebuilt {
        PREBUILT.to_string()
    } else {
        INSTALL.replace("@@BINARY_B64@@", &binary_b64)
    };
    template
        .replace("@@CONFIG_B64@@", &config_b64)
        .replace("@@DEADLINE@@", &spec.expires_at_unix.to_string())
        .replace("@@IDLE@@", &spec.idle_secs.to_string())
        .replace("@@GRACE@@", &spec.connect_grace_secs.to_string())
        .replace("@@INSTALL@@", &install)
}

fn finish_script(script: String) -> Result<String, DeployError> {
    if script.len() > 30_000 {
        return Err(DeployError::bad(
            "generated cloud-init is over 30KB; use a snapshot image instead of embedding a long config",
        ));
    }
    Ok(script)
}

const SCRIPT: &str = r#"#!/bin/bash
# Generated by echochamber. Secrets are in the base64 block, mode 0600 on disk.
set -euo pipefail
umask 077
install -d -m 700 /etc/echochamber /usr/local/lib/echochamber
base64 -d > /etc/echochamber/config.toml <<'EOF'
@@CONFIG_B64@@
EOF
chmod 600 /etc/echochamber/config.toml
printf '%s\n' '@@DEADLINE@@' > /etc/echochamber/deadline
printf '%s\n' '@@IDLE@@' > /etc/echochamber/idle-secs
printf '%s\n' '@@GRACE@@' > /etc/echochamber/connect-grace-secs
tok=$(sed -n 's/^token = "\([0-9a-f]*\)"/\1/p' /etc/echochamber/config.toml | head -n 1)
printf 'header = "Authorization: Bearer %s"\n' "$tok" > /etc/echochamber/curl.conf
chmod 600 /etc/echochamber/curl.conf
unset tok

if ! command -v ffmpeg >/dev/null 2>&1 || ! command -v curl >/dev/null 2>&1 || ! command -v iptables >/dev/null 2>&1; then
  if command -v apt-get >/dev/null 2>&1; then
    export DEBIAN_FRONTEND=noninteractive
    apt-get update -y
    apt-get install -y ffmpeg ca-certificates curl iptables
  elif command -v dnf >/dev/null 2>&1; then
    dnf install -y ffmpeg ca-certificates curl iptables
  else
    echo "need ffmpeg, curl, and iptables" >&2
    exit 1
  fi
fi

@@INSTALL@@

if [ ! -x /usr/local/bin/echochamber ]; then
  if command -v echochamber >/dev/null 2>&1; then
    ln -sf "$(command -v echochamber)" /usr/local/bin/echochamber
  else
    echo "echochamber binary not found" >&2
    exit 1
  fi
fi

cat > /etc/systemd/system/echochamber.service <<'UNIT'
[Unit]
Description=echochamber relay
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
Environment=ECHOCHAMBER_DISABLE_DEPLOY=1
ExecStart=/usr/local/bin/echochamber serve --config /etc/echochamber/config.toml
Restart=on-failure
RestartSec=2

[Install]
WantedBy=multi-user.target
UNIT

cat > /usr/local/lib/echochamber/idle.sh <<'WATCH'
#!/bin/bash
set -euo pipefail
deadline=$(cat /etc/echochamber/deadline)
idle=$(cat /etc/echochamber/idle-secs)
grace=$(cat /etc/echochamber/connect-grace-secs)
start=$(date +%s)
seen=0
down_since=0
while true; do
  now=$(date +%s)
  if [ "$now" -ge "$deadline" ]; then
    shutdown -h now "echochamber ttl"
    exit 0
  fi
  body=$(curl -fsS -m 3 -K /etc/echochamber/curl.conf http://127.0.0.1:8080/status || true)
  pub=0
  case "$body" in
    *'"publishing":true'*) pub=1 ;;
  esac
  if [ "$pub" = 1 ]; then
    seen=1
    down_since=0
  else
    if [ "$seen" = 1 ]; then
      if [ "$down_since" = 0 ]; then down_since=$now; fi
      if [ $((now - down_since)) -ge "$idle" ]; then
        shutdown -h now "echochamber idle"
        exit 0
      fi
    elif [ $((now - start)) -ge "$grace" ]; then
      shutdown -h now "echochamber connect grace"
      exit 0
    fi
  fi
  sleep 15
done
WATCH
chmod 755 /usr/local/lib/echochamber/idle.sh

cat > /etc/systemd/system/echochamber-idle.service <<'UNIT'
[Unit]
Description=echochamber idle and ttl shutdown
After=echochamber.service

[Service]
Type=simple
ExecStart=/usr/local/lib/echochamber/idle.sh
Restart=on-failure
RestartSec=2

[Install]
WantedBy=multi-user.target
UNIT

# Independent of the idle service. If that unit never starts, the box still stops.
(
  now=$(date +%s)
  deadline=$(cat /etc/echochamber/deadline)
  wait=$((deadline - now))
  if [ "$wait" -lt 1 ]; then wait=1; fi
  sleep "$wait"
  shutdown -h now "echochamber ttl"
) >/dev/null 2>&1 &

# Close the control port to everything but loopback, and hold ingest closed
# until the control endpoint answers.
iptables -I INPUT -p tcp --dport 8080 ! -i lo -j DROP
iptables -I INPUT -p tcp --dport 1935 -j DROP

systemctl daemon-reload
systemctl enable --now echochamber.service

ok=0
i=0
while [ "$i" -lt 90 ]; do
  if curl -fsS -m 2 -K /etc/echochamber/curl.conf http://127.0.0.1:8080/status | grep -q '"publishing"'; then
    ok=1
    break
  fi
  i=$((i + 1))
  sleep 2
done
if [ "$ok" != 1 ]; then
  echo "control endpoint did not respond" >&2
  shutdown -h now "echochamber control probe failed" || true
  exit 1
fi
iptables -D INPUT -p tcp --dport 1935 -j DROP

systemctl enable --now echochamber-idle.service
"#;

